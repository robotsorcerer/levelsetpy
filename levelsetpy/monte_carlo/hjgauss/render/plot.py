"""Render new analytic-solution diagnostics; never reuse old paper values.

Run from the repository root with
python -m hjgauss.render.plot --out-dir /path/to/sec_roysoc/figures
"""
import argparse
import hashlib
import json
import os
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib import font_manager
from matplotlib.font_manager import FontProperties
from matplotlib.ticker import FuncFormatter, ScalarFormatter
import numpy as np

from hjgauss.validation.benchmark import run


def _tex_scientific(value):
    mantissa, exponent = f"{value:.3e}".split("e")
    return rf"{mantissa}\times10^{{{int(exponent)}}}"


def _plot_scientific(value, _position=None):
    if value == 0:
        return "0"
    mantissa, exponent = f"{value:.1e}".split("e")
    return f"{mantissa.rstrip('0').rstrip('.')}e{int(exponent)}"


def write_numbers(record, out_dir):
    """Emit manuscript numbers solely from the newly computed native record."""
    rows = record["results"]
    full = sorted((r for r in rows if r["mode"] == "full"),
                  key=lambda r: r["steps"])
    finest = full[-1]["steps"]
    rate = [np.log(a["value_sup_error"]/b["value_sup_error"])
            /np.log(b["steps"]/a["steps"]) for a,b in zip(full[:-1],full[1:])]
    by_mode = {r["mode"]: r for r in rows if r["steps"] == finest}
    numbers = {
        "transfullValueError": _tex_scientific(by_mode["full"]["value_sup_error"]),
        "transfullDerivativeOmittedError": _tex_scientific(by_mode["drop_derivative"]["value_sup_error"]),
        "transfullHeatError": _tex_scientific(by_mode["heat"]["value_sup_error"]),
        "transfullGradientError": _tex_scientific(by_mode["full"]["gradient_sup_error"]),
        "transfullRateMin": f"{min(rate):.3f}",
        "transfullRateMax": f"{max(rate):.3f}",
        "transfullGridPoints": str(full[-1]["points"]),
        "transfullFinestSteps": str(finest),
        "transfullCoarsestSteps": str(full[0]["steps"]),
        "transfullResolutionCount": str(len(full)),
        "transfullModeCount": str(len(by_mode)),
    }
    path = Path(out_dir)/"validation_numbers.tex"
    path.write_text("% Generated by plot_1d; do not hand-edit.\n"
                    + "\n".join(rf"\newcommand{{\{key}}}{{{value}}}"
                                for key,value in numbers.items())+"\n")
    return path


def render(out_dir, placement_width_in=384.1122/72.27, figure_dir=None):
    """Recompute native diagnostic records, then produce JPEG and metadata."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    record = run()
    data_path = out_dir / "validation_records.json"
    data_path.write_text(json.dumps(record, indent=2)+"\n")
    numbers_path = write_numbers(record, out_dir)
    # Reuse the prior publication producer's bold axes/ticks and pink/cyan
    # comparison convention, with sufficient type at the declared placement.
    canvas = (6.3, 2.8)
    fonts = dict(label=10.0, tick=9.0, legend=9.0, panel=10.0)
    family = "DejaVu Sans"
    bold_face = font_manager.findfont(FontProperties(family=family, weight="bold"),
                                      fallback_to_default=False)
    plt.rcParams.update({
        "font.family": family, "font.weight": "bold",
        "axes.labelweight": "bold", "axes.titleweight": "bold",
        "axes.labelsize": fonts["label"], "axes.titlesize": fonts["panel"],
        "xtick.labelsize": fonts["tick"], "ytick.labelsize": fonts["tick"],
        "axes.linewidth": 1.2, "savefig.facecolor": "white",
    })
    fig = plt.figure(figsize=canvas, constrained_layout=True)
    grid = fig.add_gridspec(2, 2, height_ratios=[1, .14])
    axes = [fig.add_subplot(grid[0, i]) for i in range(2)]
    legend_ax = fig.add_subplot(grid[1, :])
    legend_ax.set_axis_off()
    fig.set_constrained_layout_pads(w_pad=.035, h_pad=.035, wspace=.06)
    styles = [
        ("full", "HJ-Gauss", "#C23B86", "o", "-"),
        ("heat", "Heat only", "#333333", "^", ":"),
    ]
    for ax, metric, title in zip(
        axes, ("value_sup_error", "gradient_sup_error"),
        ("(a) Value error", "(b) Gradient error"),
    ):
        for mode, label, color, marker, line in styles:
            rows = [row for row in record["results"] if row["mode"] == mode]
            ax.loglog([r["steps"] for r in rows], [r[metric] for r in rows],
                      label=label, color=color, marker=marker, linestyle=line,
                      linewidth=1.6, markersize=4.5, clip_on=True)
        ax.set_title(title, loc="left", pad=5)
        ax.set_xlabel("Time steps")
        ax.set_ylabel("Maximum error on grid")
        ax.set_xticks([100, 200, 400, 800])
        ax.xaxis.set_major_formatter(ScalarFormatter())
        ax.yaxis.set_major_formatter(FuncFormatter(_plot_scientific))
        ax.minorticks_off()
        ax.grid(True, which="major", color=".85", linewidth=.5)
        for text in ax.get_xticklabels()+ax.get_yticklabels():
            text.set_fontfamily(family)
            text.set_fontweight("bold")
    handles, labels = axes[0].get_legend_handles_labels()
    legend_ax.legend(handles, labels, loc="center", ncol=len(styles),
               frameon=False, prop=FontProperties(family=family, weight="bold",
                                                size=fonts["legend"]),
               columnspacing=1.2, handlelength=2.0)
    fig.canvas.draw()
    if placement_width_in <= 0:
        raise ValueError("placement width must be positive")
    factor = placement_width_in/canvas[0]
    effective = {role: size*factor for role,size in fonts.items()}
    if min(effective.values()) < 7:
        raise ValueError("declared placement makes a font role smaller than 7 pt")
    figure_dir = Path(figure_dir) if figure_dir is not None else out_dir
    figure_dir.mkdir(parents=True, exist_ok=True)
    path = figure_dir / "hjgauss_validation.jpg"
    fig.savefig(path,dpi=300,facecolor='white',pil_kwargs={'quality':98,'subsampling':0,'optimize':True})
    plt.close(fig)
    metadata = {
        "scope": "Deterministic one-dimensional periodic analytic verification",
        "producer": "plot_1d.render",
        "data_producer": "benchmark.run",
        "data_file": data_path.name,
        "data_sha256": hashlib.sha256(data_path.read_bytes()).hexdigest(),
        "numbers_file": numbers_path.name,
        "numbers_sha256": hashlib.sha256(numbers_path.read_bytes()).hexdigest(),
        "figure_file": os.path.relpath(path.resolve(), out_dir.resolve()),
        "figure_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "canvas_width_in": canvas[0], "canvas_height_in": canvas[1],
        "dpi": 300, "placement_width_in": placement_width_in,
        "uniform_scale_factor": factor, "font_family": family,
        "font_weight": "bold", "font_face_file": bold_face,
        "source_font_pt": fonts, "effective_font_pt": effective,
        "layout": "constrained_layout; no tight bounding-box resize",
        "grayscale_mapping": {mode: {"marker": marker, "line": line}
                              for mode, label, color, marker, line in styles},
        "clipping": "intentional data clipping at axes; text and legend unclipped",
    }
    (out_dir/"validation_figure_metadata.json").write_text(
        json.dumps(metadata, indent=2)+"\n")
    return metadata


if __name__ == "__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", required=True)
    parser.add_argument("--placement-width-in", type=float, default=384.1122/72.27)
    parser.add_argument("--figure-dir", help="JPEG directory; numerical records remain in --out-dir")
    args=parser.parse_args()
    meta=render(args.out_dir,args.placement_width_in,args.figure_dir)
    print(json.dumps({"figure": meta["figure_file"],
                      "effective_font_pt": meta["effective_font_pt"]},indent=2))
