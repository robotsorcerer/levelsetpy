"""Generate manuscript numbers and tables solely from native validation data."""
from pathlib import Path
import argparse,json
from hjgauss.validation.report import assess

NAMES={'double_integrator':'Double integrator','dubins_single':'Single Dubins',
       'dubins_relative':'Dubins vehicles','rockets':'Rockets','murmuration':'Bird model'}


def number(x):
    if x is None:return r'\text{pending}'
    if abs(x)==0:return '0'
    if .001<=abs(x)<1000:return f'{x:.4g}'
    mantissa,exponent=f'{x:.2e}'.split('e')
    return rf'{mantissa}\times10^{{{int(exponent)}}}'


def generate(root,paper,selection):
    summary=assess(root,selection)
    out=paper/'sec_roysoc/figures';out.mkdir(parents=True,exist_ok=True)
    macros=[]
    pop=summary['population'] if summary['population'].get('passed') else {}
    for macro,key in [('NDPopulationCount','count'),('NDPopulationFinite','finite_count'),
                      ('NDPopulationPositive','positive_count'),('NDPopulationDisagreements','sign_disagreement_count'),
                      ('NDPopulationBothNonpositive','both_nonpositive_count')]:
        value=f"{pop[key]:,}".replace(',',r'{,}') if key in pop else r'\text{pending}'
        macros.append('\\newcommand{\\'+macro+'}{'+value+'}')
    for macro,field in [('NDPopulationError','sampled_absolute_discrepancy'),
                        ('NDPopulationDisagreementReferenceMax','max_reference_magnitude_at_disagreement')]:
        macros.append('\\newcommand{\\'+macro+'}{'+number(pop.get(field))+'}')
    topology=summary.get('topology',{})
    times=topology.get('times',[]) if topology.get('passed') else []
    fine=topology.get('fine_counts',[]) if times else []
    holes=[i for i,row in enumerate(fine) if row[1]>0]
    last=holes[-1] if holes else None
    first=next((i for i in range(last+1,len(times)) if fine[i][1]==0),None) if last is not None else None
    for macro,value in [('NDTopologyTimeCount',str(len(times)) if times else None),
                        ('NDTopologyLastHoleTime',f'{times[last]:.1f}' if last is not None else None),
                        ('NDTopologyFirstNoHoleTime',f'{times[first]:.1f}' if first is not None else None)]:
        macros.append('\\newcommand{\\'+macro+'}{'+(value or r'\text{pending}')+'}')
    for rec in summary['analytic']:
        prefix=('FD' if rec.get('scheme')=='fd' else '')+('Full' if rec['kind']=='full' else 'Reference')
        macros.append('\\newcommand{\\NDAnalytic'+prefix+('Two' if rec['dimension']==2 else 'Three')+'}{'+number(rec.get('error'))+'}')
    (out/'multidimensional_numbers.tex').write_text('% Generated by hjgauss.render.latex; no manual numeric edits.\n'+'\n'.join(macros)+'\n')
    table=[r'\begin{table}[tbp]',r'\centering',
       r'\caption{Maximum sampled discrepancies for the HJ-Gauss computations. Refinement and Levelset Reference columns use the common observation queries; the residual column gives the largest sampled original-equation residual over native states at three interior times. All payoffs are dimensionless. The grid column lists the fine spatial and heading counts. Pending or failed checks are disclosed in the reproducibility record.}',
       r'\label{tab:error_comparison}',r'\setlength{\tabcolsep}{4pt}',r'\begin{tabular}{lccccc}',r'\toprule',
       r'\textbf{System} & \textbf{Grid} & \textbf{Refinement} & \textbf{Levelset Reference} & \textbf{Residual} & \textbf{Status}\\',r'\midrule']
    sensitivity=[r'\begin{table}[tbp]',r'\centering',
       r'\caption{Maximum sampled changes under time halving, coefficient variation, isolated boundary extension, and combined box sensitivity. Boundary extension fixes the Levelset Reference time step, spacing, heading count, Hamiltonian, and initial condition on the common box. The combined test also changes the time step and coefficient wavelength. Payoffs are normalized.}',
       r'\label{tab:nd-sensitivity}',r'\begin{tabular}{lcccc}',r'\toprule',
       r'\textbf{System} & \textbf{Time} & \textbf{Coefficient} & \textbf{Boundary} & \textbf{Combined box}\\',r'\midrule']
    for name in ['rockets','dubins_relative','dubins_single','double_integrator','murmuration']:
        r=summary['cases'][name];rec=r.get('record',{});shape=rec.get('shape')
        grid=(str(shape[0])+'^2'+(r'\times'+str(shape[2]) if len(shape)==3 else '')) if shape else r'\text{pending}'
        vals=[r.get(k,{}).get('sup') for k in ['space','independent']]
        vals.append(rec.get('original_residual_sup'))
        status='Pass' if r.get('passed') else 'Fail' if any(not g['passed'] for g in r.get('gates',{}).values()) else 'Pending'
        table.append(NAMES[name]+' & $'+grid+'$ & '+' & '.join('$'+number(v)+'$' for v in vals)+' & '+status+r'\\')
        vals=[r.get(k,{}).get('sup') for k in ['time','coefficient','boundary','domain']]
        sensitivity.append(NAMES[name]+' & '+' & '.join('$'+number(v)+'$' for v in vals)+r'\\')
    for lines,name in [(table,'multidimensional_table.tex'),(sensitivity,'multidimensional_sensitivity.tex')]:
        lines.extend([r'\bottomrule',r'\end{tabular}',r'\end{table}'])
        (out/name).write_text('% Generated by hjgauss.render.latex.\n'+'\n'.join(lines)+'\n')
    return summary


def main():
    p=argparse.ArgumentParser();p.add_argument('--root',type=Path,default=Path('results/multidimensional'))
    p.add_argument('--paper-root',type=Path,required=True);p.add_argument('--selection',type=Path)
    a=p.parse_args();selection=json.loads(a.selection.read_text()) if a.selection else None
    s=generate(a.root,a.paper_root,selection)
    print('Generated tables; overall numerical gates passed:',s['passed'])

if __name__=='__main__':main()
